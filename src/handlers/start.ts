import { BotContext } from "../types";
import { Database } from "../db/database";
import { mainReplyKeyboard } from "./keyboards";

export async function handleStart(ctx: BotContext): Promise<void> {
  const user = ctx.from;
  if (!user) return;

  const db = new Database(ctx.env.DB);
  await db.ensureDefaultAccount(user.id, ctx.env.DEFAULT_ACCOUNT_NAME || "حساب اصلی");

  const welcomeMessage = `
👋 سلام ${user.first_name || "کاربر گرامی"}! به **حساب‌یار (HesabYar)** خوش آمدید.

من دستیار هوشمند حسابداری شخصی شما روی کلادفلر هستم.

✨ **امکانات ویژه:**
• 🔘 **ثبت آسان مرحله به مرحله:** با زدن دکمه‌های «➕ ثبت واریز» یا «➖ ثبت برداشت»، مبلغ و دسته‌بندی و حساب را فقط با دکمه‌های شیشه‌ای انتخاب کنید.
• 📷 **خواندن عکس رسید:** عکس رسید یا فاکتور را بفرستید تا هوش مصنوعی مبلغ، تاریخ و دسته‌بندی را استخراج کند.
• 🎙 **دستیار صوتی (ویس):** یک پیام صوتی بفرستید (مثلاً: *«پنجاه تومن دادم بنزین»*).
• ✉️ **تحلیل پیامک بانکی:** متن پیامک تراکنش بانک را کپی کنید تا خودکار ثبت شود.
• 💳 **حساب‌ها و کارت‌ها:** افزودن کارت و بانک از فهرست بانک‌های کشور و محاسبه مانده لحظه‌ای.
• 📊 **گزارش‌گیری پیشرفته:** خلاصه ماهانه با **فایل اکسل (.xlsx)** و **نمودارهای تحلیلی**.

برای شروع از دکمه‌های منوی زیر استفاده کنید:
  `.trim();

  await ctx.reply(welcomeMessage, {
    parse_mode: "Markdown",
    reply_markup: mainReplyKeyboard(),
  });
}

export async function handleHelp(ctx: BotContext): Promise<void> {
  const helpText = `
📖 **راهنمای استفاده از حساب‌یار:**

۱. **ثبت مرحله به مرحله (توصیه شده):**
   • دکمه «➕ ثبت واریز» یا «➖ ثبت برداشت» را بزنید.
   • مبلغ، دسته‌بندی و حساب را به آسانی با دکمه‌های شیشه‌ای انتخاب کنید.

۲. **ثبت با عکس رسید:**
   • کافیست هر نوع عکس رسید یا فاکتور خرید را بفرستید.

۳. **ثبت با ویس فارسی:**
   • یک ویس بفرستید و بگویید چه مبلغی برای چه کاری خرج شد.

۴. **افزودن حساب و کارت بانکی:**
   • از منوی «💳 حساب‌ها و کارت‌ها»، دکمه «➕ افزودن حساب جدید» را بزنید و بانک خود را انتخاب کنید.

۵. **گزارش‌ها:**
   • با زدن «📊 گزارش ماه جاری» یا دستور \`/report\` نمودار و خروجی اکسل بگیرید.

۶. **لغو عملیات:**
   • هر زمان که خواستید می‌توانید دستور \`/cancel\` را ارسال کنید.
  `.trim();

  await ctx.reply(helpText, { parse_mode: "Markdown" });
}
